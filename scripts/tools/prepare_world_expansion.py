# Original parrot sheet has an RGB checkerboard. Flood only the neutral exterior.
source=Image.open(ROOT/'assets/Cute Teal Parrot Sprite Sheet.png').convert('RGB')
output=ROOT/'assets/pets/parrot'
output.mkdir(parents=True,exist_ok=True)
poses={'front':(12,12,250,184),'side_1':(266,16,499,184),'side_2':(511,16,746,184),'side_3':(762,16,996,184),'side_4':(1007,16,1240,184),'back_1':(12,390,249,548),'back_2':(266,390,499,548)}
for name,rect in poses.items():
    crop=source.crop(rect)
    w,h=crop.size
    barrier=Image.new('L',crop.size)
    barrier.putdata([255 if max(r,g,b)-min(r,g,b)>35 or max(r,g,b)<95 else 0 for r,g,b in crop.getdata()])
    wall=barrier.filter(ImageFilter.MaxFilter(3)).load()
    outside=set()
    queue=deque([(x,y) for x in range(w) for y in [0,h-1]]+[(x,y) for y in range(h) for x in [0,w-1]])
    while queue:
        x,y=queue.popleft()
        if not (0<=x<w and 0<=y<h) or (x,y) in outside or wall[x,y]: continue
        outside.add((x,y))
        queue.extend([(x-1,y),(x+1,y),(x,y-1),(x,y+1)])
    alpha=Image.new('L',crop.size)
    alpha.putdata([0 if (x,y) in outside else 255 for y in range(h) for x in range(w)])
    crop=crop.convert('RGBA'); crop.putalpha(alpha)
    crop=crop.crop(alpha.getbbox()); crop.thumbnail((116,102),Image.Resampling.LANCZOS)
    canvas=Image.new('RGBA',(128,128)); canvas.alpha_composite(crop,((128-crop.width)//2,(128-crop.height)//2))
    canvas.save(output/(name+'.png'))
