ROOT = Path(__file__).resolve().parents[2]
def vector(block, field, default=(0, 0)):
    match = re.search(r'^'+field+r' = Vector2\(([^)]+)\)', block, re.M)
    return list(map(float, match[1].split(','))) if match else list(default)
def point(p): return [round(24+p[0]*.8625, 3), round(204+p[1]*436/720, 3)]
def parse_scene(path, glacial=False):
    text = path.read_text(encoding='utf-8')
    resources = {i:p for p,i in re.findall(r'\[ext_resource type="[^"]+" path="([^"]+)" id="([^"]+)"', text)}
    shapes = {}
    for block in re.split(r'(?=\[sub_resource )', text)[1:]:
        match = re.match(r'\[sub_resource type="([^"]+)" id="([^"]+)"', block)
        if match[1]=='RectangleShape2D': shapes[match[2]]={'size':vector(block,'size')}
        elif match[1]=='CircleShape2D': shapes[match[2]]={'radius':float(re.search(r'radius = ([\d.]+)',block)[1])}
    data={'objects':[], 'collisions':[]}
    positions={'.':[0,0], 'Objetos':[0,0]}
    for block in re.split(r'(?=\[node )', text)[1:]:
        match = re.match(r'\[node name="([^"]+)" type="([^"]+)"(?: parent="([^"]+)")?',block)
        if not match: continue
        name,kind,parent=match.groups()
        parent=parent or '.'
        local=vector(block,'position')
        base=positions.get(parent,[0,0])
        absolute=[base[0]+local[0],base[1]+local[1]]
        positions[(parent+'/' if parent!='.' else '')+name]=absolute
        if path.stem=='loja_cosmeticos' and ('Pufe1' in name or 'Pufe1' in parent):
            continue
        if kind=='Sprite2D' and name not in ['Espelho','Brilho']:
            texture=re.search(r'texture = ExtResource\("([^"]+)"\)',block)
            if not texture: continue
            texture=resources[texture[1]]
            if glacial:
                texture=texture.replace('res://cenario/','res://assets/cenario/glacial_ia/cenario/').replace('res://elementos/','res://assets/cenario/glacial_ia/elementos/')
            if name in ['Fundo','Chao']:
                data['ground']=texture
                continue
            scale=vector(block,'scale',(1,1))
            data['objects'].append({'name':name,'texture':texture,'position':point(absolute),'offset':vector(block,'offset'),'scale':[s*436/720 for s in scale],'centered':'centered = false' not in block, 'depth':round(point(absolute)[1]) if name!='LagoFossil' else 0})
        elif kind=='CollisionShape2D' and 'Objetos/' in parent and '/Area' not in parent:
            shape=re.search(r'shape = SubResource\("([^"]+)"\)',block)
            if shape and shape[1] in shapes:
                value=shapes[shape[1]].copy()
                value['position']=point(absolute)
                if 'size' in value: value['size']=[s*436/720 for s in value['size']]
                else: value['radius']*=436/720
                data['collisions'].append(value)
    return data

layouts={name:parse_scene(ROOT/f'artwork/MundoDosUrsos3/cenas/{name}.tscn') for name in ['loja_pets','loja_cosmeticos','provador']}
layouts['language']=parse_scene(ROOT/'artwork/porto-glacial-ia/cenas/porto_glacial.tscn',True)
runtime=ROOT/'assets/cenario/glacial_runtime'
runtime.mkdir(parents=True,exist_ok=True)
ratios={}
for path in (ROOT/'assets/cenario/glacial_ia').rglob('*.png'):
    image=Image.open(path).convert('RGBA')
    original=image.size
    image.thumbnail((1280,720) if path.name=='chao-glacial.png' else (640,640),Image.Resampling.LANCZOS)
    image.save(runtime/path.name)
    ratios[path.name]=(image.width/original[0],image.height/original[1])
for item in layouts['language']['objects']:
    name=Path(item['texture']).name
    ratio=ratios[name]
    item['texture']='res://assets/cenario/glacial_runtime/'+name
    item['offset']=[value*ratio[i] for i,value in enumerate(item['offset'])]
    item['scale']=[value/ratio[i] for i,value in enumerate(item['scale'])]
    if item['name']=='Navio':
        item['scale']=[value*1.3 for value in item['scale']]
        item['texture']='res://assets/cenario/glacial_runtime/navio-polar-aberto.png'
import subprocess, sys
